impl Rule for EconomicCrimeDeepRules {
    fn metadata(&self) -> &RuleMetadata {
        &self.metadata
    }

    fn category(&self) -> RuleCategory {
        RuleCategory::law("economic_crime_deep")
    }

    fn validate(&self, _ctx: &ValidateContext) -> RuleResult<bool> {
        Ok(true)
    }

    fn explain(&self) -> String {
        crate::rules::core::format_rule_sections(
            "经济犯罪深度规则",
            &[
                ("金融犯罪详解", &self.financial_crimes_detailed()),
                ("税收犯罪详解", &self.tax_crimes_detailed()),
                ("商业犯罪详解", &self.commercial_crimes_detailed()),
                ("网络经济犯罪详解", &self.cyber_economic_crimes_detailed()),
                ("证券犯罪详解", &self.securities_crimes_detailed()),
                ("侵犯知识产权罪详解", &self.ip_crimes_detailed()),
            ],
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_economic_crime_deep_rules() {
        let rules = EconomicCrimeDeepRules::new();
        assert_eq!(rules.metadata().name, "经济犯罪深度规则");
        assert!(!rules.financial_crimes_detailed().is_empty());
        assert!(!rules.tax_crimes_detailed().is_empty());
        assert!(!rules.commercial_crimes_detailed().is_empty());
        assert!(!rules.cyber_economic_crimes_detailed().is_empty());
        assert!(!rules.securities_crimes_detailed().is_empty());
        assert!(!rules.ip_crimes_detailed().is_empty());
        assert!(!rules.explain().is_empty());
    }

    #[test]
    fn test_crime_sections_count() {
        let rules = EconomicCrimeDeepRules::new();
        assert_eq!(rules.financial_crimes_detailed().len(), 10);
        assert_eq!(rules.tax_crimes_detailed().len(), 10);
        assert_eq!(rules.commercial_crimes_detailed().len(), 10);
        assert_eq!(rules.cyber_economic_crimes_detailed().len(), 10);
        assert_eq!(rules.securities_crimes_detailed().len(), 9);
        assert_eq!(rules.ip_crimes_detailed().len(), 8);
    }
}
