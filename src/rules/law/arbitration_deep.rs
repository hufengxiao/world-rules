impl Rule for ArbitrationDeepRules {
    fn metadata(&self) -> &RuleMetadata {
        &self.metadata
    }

    fn category(&self) -> RuleCategory {
        RuleCategory::law("arbitration_deep")
    }

    fn validate(&self, _ctx: &ValidateContext) -> RuleResult<bool> {
        Ok(true)
    }

    fn explain(&self) -> String {
        crate::rules::core::format_rule_sections(
            "仲裁法深度规则",
            &[
                ("申请程序", &self.application_procedure_detailed()),
                ("审理程序", &self.hearing_procedure_detailed()),
                ("裁决规则", &self.award_rules_detailed()),
                ("执行程序", &self.execution_procedure_detailed()),
                ("特殊程序", &self.special_procedures_detailed()),
                ("费用规则", &self.cost_rules_detailed()),
            ],
        )
    }
}

