impl Rule for AILawDeepRules {
    fn metadata(&self) -> &RuleMetadata {
        &self.metadata
    }

    fn category(&self) -> RuleCategory {
        RuleCategory::law("ai_law_deep")
    }

    fn validate(&self, _ctx: &ValidateContext) -> RuleResult<bool> {
        Ok(true)
    }

    fn explain(&self) -> String {
        crate::rules::core::format_rule_sections(
            "人工智能法深度规则",
            &[
                ("AI系统分类", &self.ai_system_classification_detailed()),
                ("算法透明度", &self.algorithm_transparency_detailed()),
                ("数据安全", &self.ai_data_security_detailed()),
                ("伦理审查", &self.ai_ethics_review_detailed()),
                ("安全责任", &self.ai_safety_liability_detailed()),
            ],
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_ai_law_deep_rules() {
        let rules = AILawDeepRules::new();
        assert_eq!(rules.metadata().name, "人工智能法深度规则");

        // 测试各个方法
        assert!(!rules.ai_system_classification_detailed().is_empty());
        assert!(!rules.algorithm_transparency_detailed().is_empty());
        assert!(!rules.ai_data_security_detailed().is_empty());
        assert!(!rules.ai_ethics_review_detailed().is_empty());
        assert!(!rules.ai_safety_liability_detailed().is_empty());
    }

    #[test]
    fn test_explain() {
        let rules = AILawDeepRules::new();
        let explanation = rules.explain();
        assert!(explanation.contains("AI系统分类"));
        assert!(explanation.contains("算法透明度"));
        assert!(explanation.contains("数据安全"));
    }
}
