impl Rule for ConsumerProtectionDeepRules {
    fn metadata(&self) -> &RuleMetadata {
        &self.metadata
    }

    fn category(&self) -> RuleCategory {
        RuleCategory::law("consumer_protection_deep")
    }

    fn validate(&self, _ctx: &ValidateContext) -> RuleResult<bool> {
        Ok(true)
    }

    fn explain(&self) -> String {
        crate::rules::core::format_rule_sections(
            "消费者权益保护法深度规则",
            &[
                ("消费者权利", &self.consumer_rights_detailed()),
                ("经营者义务", &self.operator_obligations_detailed()),
                ("产品质量规则", &self.product_quality_detailed()),
                ("不正当行为规则", &self.unfair_practices_detailed()),
                ("电子商务规则", &self.e_commerce_rules_detailed()),
                ("争议解决规则", &self.dispute_resolution_detailed()),
                ("特殊保护规则", &self.special_protection_detailed()),
            ],
        )
    }
}

