impl Rule for CybersecurityLawDeepRules {
    fn metadata(&self) -> &RuleMetadata {
        &self.metadata
    }

    fn category(&self) -> RuleCategory {
        RuleCategory::law("cybersecurity_law_deep")
    }

    fn validate(&self, _ctx: &ValidateContext) -> RuleResult<bool> {
        Ok(true)
    }

    fn explain(&self) -> String {
        crate::rules::core::format_rule_sections(
            "网络安全法深度规则",
            &[
                ("等级保护", &self.level_protection_detailed()),
                ("关键信息基础设施", &self.critical_infrastructure_detailed()),
                ("个人信息保护", &self.personal_info_protection_detailed()),
                ("安全事件处置", &self.security_incident_handling_detailed()),
                ("安全审查", &self.security_review_detailed()),
            ],
        )
    }
}

