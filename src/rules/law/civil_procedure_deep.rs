impl Rule for CivilProcedureDeepRules {
    fn metadata(&self) -> &RuleMetadata {
        &self.metadata
    }

    fn category(&self) -> RuleCategory {
        RuleCategory::law("civil_procedure_deep")
    }

    fn validate(&self, _ctx: &ValidateContext) -> RuleResult<bool> {
        Ok(true)
    }

    fn explain(&self) -> String {
        crate::rules::core::format_rule_sections(
            "民事诉讼法深度规则",
            &[
                ("诉讼一般规则", &self.procedure_general_detailed()),
                ("当事人规则", &self.parties_rules_detailed()),
                ("证据规则", &self.evidence_rules_detailed()),
                ("审判程序", &self.trial_procedure_detailed()),
                ("上诉规则", &self.appeal_rules_detailed()),
                ("执行规则", &self.execution_rules_detailed()),
                ("特别程序", &self.special_procedure_detailed()),
            ],
        )
    }
}

