impl Rule for EnvironmentalLawDeepRules {
    fn metadata(&self) -> &RuleMetadata {
        &self.metadata
    }

    fn category(&self) -> RuleCategory {
        RuleCategory::law("environmental_law_deep")
    }

    fn validate(&self, _ctx: &ValidateContext) -> RuleResult<bool> {
        Ok(true)
    }

    fn explain(&self) -> String {
        crate::rules::core::format_rule_sections(
            "环境法深度规则",
            &[
                (
                    "环境影响评价",
                    &self.environmental_impact_assessment_detailed(),
                ),
                ("排污许可", &self.discharge_permit_detailed()),
                ("环境污染责任", &self.pollution_liability_detailed()),
                (
                    "环境公益诉讼",
                    &self.environmental_public_interest_litigation(),
                ),
                ("生态保护", &self.ecological_protection_detailed()),
            ],
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_environmental_law_deep_rules() {
        let rules = EnvironmentalLawDeepRules::new();
        assert_eq!(rules.metadata().name, "环境法深度规则");

        // 测试各个方法
        assert!(!rules.environmental_impact_assessment_detailed().is_empty());
        assert!(!rules.discharge_permit_detailed().is_empty());
        assert!(!rules.pollution_liability_detailed().is_empty());
        assert!(!rules.environmental_public_interest_litigation().is_empty());
        assert!(!rules.ecological_protection_detailed().is_empty());
    }

    #[test]
    fn test_explain() {
        let rules = EnvironmentalLawDeepRules::new();
        let explanation = rules.explain();
        assert!(explanation.contains("环境影响评价"));
        assert!(explanation.contains("排污许可"));
        assert!(explanation.contains("环境污染责任"));
    }
}
