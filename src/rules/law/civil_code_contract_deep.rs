impl Rule for CivilCodeContractDeepRules {
    fn metadata(&self) -> &RuleMetadata {
        &self.metadata
    }

    fn category(&self) -> RuleCategory {
        RuleCategory::law("civil_code_contract_deep")
    }

    fn validate(&self, _ctx: &ValidateContext) -> RuleResult<bool> {
        Ok(true)
    }

    fn explain(&self) -> String {
        crate::rules::core::format_rule_sections(
            "民法典合同编深度规则",
            &[
                ("合同订立规则", &self.contract_form_detailed()),
                ("合同效力规则", &self.contract_effect_detailed()),
                ("合同履行规则", &self.contract_performance_detailed()),
                ("合同保全规则", &self.contract_preservation_detailed()),
                ("合同变更转让规则", &self.contract_modification_detailed()),
                ("合同终止规则", &self.contract_termination_detailed()),
                ("违约责任规则", &self.breach_liability_detailed()),
                ("典型合同规则", &self.typical_contract_detailed()),
            ],
        )
    }
}

