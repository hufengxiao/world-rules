impl Rule for LaborLawDeepRules {
    fn metadata(&self) -> &RuleMetadata {
        &self.metadata
    }

    fn category(&self) -> RuleCategory {
        RuleCategory::law("labor_law_deep")
    }

    fn validate(&self, _ctx: &ValidateContext) -> RuleResult<bool> {
        Ok(true)
    }

    fn explain(&self) -> String {
        crate::rules::core::format_rule_sections(
            "劳动法深度规则",
            &[
                ("劳动关系规则", &self.labor_relations_detailed()),
                ("劳动者权利", &self.worker_rights_detailed()),
                ("用人单位义务", &self.employer_obligations_detailed()),
                ("合同解除终止", &self.contract_termination_detailed()),
                ("工作时间规则", &self.working_time_rules_detailed()),
                ("工资报酬规则", &self.wage_rules_detailed()),
                ("社会保险规则", &self.social_insurance_rules_detailed()),
            ],
        )
    }
}

