def make_module(cat, name, cn, desc, origin, tags, sections):
    """生成一个规则模块文件"""
    tag_s = ", ".join('"' + t + '"' for t in tags)
    meth = ""
    calls = ""
    for sn, items in sections:
        mn = sn.replace("/", "_").replace(" ", "_").replace("（", "").replace("）", "")
        # 取前两个汉字做方法名
        mn = "section_" + str(sections.index((sn, items)))
        il = ", ".join('"' + i + '"' for i in items)
        meth += "    pub fn " + mn + "(&self) -> Vec<&'static str> {\n"
        meth += "        vec![" + il + "]\n    }\n\n"
        calls += '            ("' + sn + '", &self.' + mn + '()),\n'
    return '''//! {cn}

use crate::rules::core::{{format_rule_sections, Rule, RuleCategory, RuleMetadata, RuleResult}};
use crate::simple_rule;

simple_rule! {{
    struct: {name}Rules,
    name: "{cn}",
    desc: "{desc}",
    origin: "{origin}",
    tags: [{tags}]
}}

impl {name}Rules {{
{meth}}}

impl Rule for {name}Rules {{
    fn metadata(&self) -> &RuleMetadata {{ &self.metadata }}
    fn category(&self) -> RuleCategory {{ RuleCategory::{cat}("{name}") }}
    fn validate(&self, ctx: &str) -> RuleResult<bool> {{ Ok(!ctx.is_empty()) }}
    fn explain(&self) -> String {{
        format_rule_sections("{cn}", &[{calls}])
    }}
}}

#[cfg(test)]
mod tests {{
    use super::*;
    #[test]
    fn test_{name}_rules() {{
        let r = {name}Rules::new();
        assert!(!r.metadata().name.is_empty());
        assert!(!r.explain().is_empty());
    }}
}}
'''.format(cat=cat, name=name, cn=cn, desc=desc, origin=origin, tags=tag_s,
           meth=meth, calls=calls)

