# 同 gen_sport 但 category 为 social/science/law/health
def gen_other(cat, name, cn_name, desc, origin, tags, sections):
    tag_str = ", ".join(f'"{t}"' for t in tags)
    section_methods = ""
    section_calls = ""
    for sname, items in sections:
        method_name = sname.replace(" ", "_").lower()
        items_str = ", ".join(f'"{item}"' for item in items)
        section_methods += f"""
    /// {sname}
    pub fn {method_name}(&self) -> Vec<&'static str> {{
        vec![{items_str}]
    }}
"""
        section_calls += f'            ("{sname}", &self.{method_name}()),\n'

    cat_fn = cat
    return f"""//! {cn_name}

use crate::rules::core::{{format_rule_sections, Rule, RuleCategory, RuleMetadata, RuleResult}};
use crate::simple_rule;

simple_rule! {{
    struct: {name}Rules,
    name: "{cn_name}",
    desc: "{desc}",
    origin: "{origin}",
    tags: [{tag_str}]
}}

impl {name}Rules {{
{section_methods}}}

impl Rule for {name}Rules {{
    fn metadata(&self) -> &RuleMetadata {{
        &self.metadata
    }}

    fn category(&self) -> RuleCategory {{
        RuleCategory::{cat_fn}("{name}")
    }}

    fn validate(&self, context: &str) -> RuleResult<bool> {{
        Ok(!context.is_empty())
    }}

    fn explain(&self) -> String {{
        format_rule_sections(
            "{cn_name}",
            &[
{section_calls}            ],
        )
    }}
}}

#[cfg(test)]
mod tests {{
    use super::*;

    #[test]
    fn test_{name}_rules() {{
        let rules = {name}Rules::new();
        assert!(!rules.metadata().name.is_empty());
    }}
}}
"""

